AIGU = {2: 0x02, 3: 0x01}
GRAVE = {2: 0x01, 3: 0x02}
CIRC = {1: 0x02, 2: 0x01, 3: 0x02}
TREMA = {1: 0x02, 3: 0x02}


def accent(base, marks, clear_dot=False):
    cols = list(GLYPHS[base])
    if clear_dot:                    # î / ï : le point du i disparaît
        cols = [c & ~0x01 for c in cols]
    for i, m in marks.items():
        cols[i] |= m
    return cols


GLYPHS.update({
    'à': accent('a', GRAVE), 'â': accent('a', CIRC), 'ä': accent('a', TREMA),
    'é': accent('e', AIGU), 'è': accent('e', GRAVE),
    'ê': accent('e', CIRC), 'ë': accent('e', TREMA),
    'î': accent('i', CIRC, True), 'ï': accent('i', TREMA, True),
    'ô': accent('o', CIRC), 'ö': accent('o', TREMA),
    'ù': accent('u', GRAVE), 'û': accent('u', CIRC), 'ü': accent('u', TREMA),
    'ç': accent('c', {2: 0x80}),
})


def to_rows(cols):
    rows = []
    for r in range(8):
        b = 0
        for c in range(5):
            if cols[c] & (1 << r):
                b |= 0x80 >> (c + 1)
        rows.append(b)
    return rows


def main():
    out = ["// Police bitmap 5×7 (grille 8×8) générée par tools/gen_font.py.",
           "// 8 octets par glyphe, un par ligne, bit 7 = colonne de gauche.",
           "export const FONT = {"]
    for ch, cols in GLYPHS.items():
        rows = to_rows(cols)
        key = ch.replace('\\', '\\\\').replace("'", "\\'")
        out.append(f"  '{key}': [{', '.join(f'0x{b:02X}' for b in rows)}],")
    out.append("};\n")
    Path('web/js/font.js').write_text('\n'.join(out), encoding='utf-8')
    print(f"web/js/font.js : {len(GLYPHS)} glyphes")


if __name__ == '__main__':
    main()
